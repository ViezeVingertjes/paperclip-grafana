#!/usr/bin/env python3
"""Generate the "Paperclip" Grafana dashboard JSON (traces, plus the metrics derived from them).

Usage (from the repo root): python3 tools/gen_dashboard.py > dashboards/paperclip.json

Signals (Paperclip server with opt-in OpenTelemetry, last checked against commit b31ec0a, OTLP -> grafana/otel-lgtm):
  Paperclip exports TRACES ONLY (no metrics, no logs). Everything below is derived from those spans:
  Prometheus  traces_spanmetrics_{calls_total,latency_bucket,latency_sum,latency_count}{service, span_name, status_code}
              generated by Tempo from the spans
  Tempo       TraceQL metrics (`{...} | rate() / count_over_time() / quantile_over_time(duration, ...) by (...)`)
              and TraceQL searches for the trace tables

Why two sources of derived metrics
  * Span metrics are cheap, live in Prometheus and give exact counts, error ratios and mean durations, but their latency
    histogram stops at 16.4 s and carries no span attributes. Agent runs last minutes, so every percentile of a run, a
    turn or a startup comes from TraceQL metrics instead, which has no such cap and can group by any span attribute
    (provider, tool, cache outcome, HTTP route ...).
  * Ratio tiles ("vs usual") need division across two ranges, which only PromQL can do. They therefore use counts and
    mean durations (sum / count, exact at any length) from span metrics.

Design notes
  * Span names and attributes come from doc/observability.md and the source of Paperclip (server/src/services/...).
    The list of what the dashboard reads is in docs/telemetry-reference.md.
  * Reading order: Health -> Overview -> Runs -> Startup -> Turns and tools -> Providers -> Workspace -> Controller ->
    Budget -> API and database -> Chat -> Traces -> Telemetry pipeline.
"""
