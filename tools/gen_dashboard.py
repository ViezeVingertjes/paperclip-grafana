#!/usr/bin/env python3
"""Generate the "Paperclip" Grafana dashboard JSON (traces, plus the metrics derived from them).

Usage (from the repo root): python3 tools/gen_dashboard.py > dashboards/paperclip.json

Signals (Paperclip server with opt-in OpenTelemetry, last checked against commit b31ec0a, OTLP -> grafana/otel-lgtm):
  Paperclip exports TRACES ONLY (no metrics, no logs). Everything below is derived from those spans:
  Prometheus  traces_spanmetrics_{calls_total,latency_bucket,latency_sum,latency_count}{service, span_name, status_code}
              generated by Tempo from the spans
  Tempo       TraceQL metrics (`{...} | rate() / count_over_time() / quantile_over_time(duration, ...) by (...)`)
              and TraceQL searches for the trace tables

Why two sources of derived metrics
  * Span metrics are cheap, live in Prometheus and give exact counts, error ratios and mean durations, but their latency
    histogram stops at 16.4 s and carries no span attributes. Agent runs last minutes, so every percentile of a run, a
    turn or a startup comes from TraceQL metrics instead, which has no such cap and can group by any span attribute
    (provider, tool, cache outcome, HTTP route ...).
  * Ratio tiles ("vs usual") need division across two ranges, which only PromQL can do. They therefore use counts and
    mean durations (sum / count, exact at any length) from span metrics.

Design notes
  * Span names and attributes come from doc/observability.md and the source of Paperclip (server/src/services/...).
    The list of what the dashboard reads is in docs/telemetry-reference.md.
  * Reading order: Health -> Overview -> Runs -> Run preparation -> Execution and completion -> Native runner (startup,
    turns and tools, providers) -> Workspace -> Controller -> Budget -> API -> Chat -> Traces -> Telemetry pipeline.
  * Runs are task.execution_attempt, which every adapter emits; the native runner rows need paperclip_runner agents.
"""
import json

# Datasources are dashboard variables, so the dashboard imports into any Grafana: each variable picks the first
# datasource of its type (change it under Dashboard settings > Variables if you have several).
PROM = {"type": "prometheus", "uid": "${ds_prometheus}"}
TEMPO = {"type": "tempo", "uid": "${ds_tempo}"}
DATASOURCE_VARS = [
    {"name": f"ds_{kind}", "label": label, "type": "datasource", "query": kind, "hide": 2, "refresh": 1,
     "includeAll": False, "multi": False, "current": {}, "options": []}
    for kind, label in (("prometheus", "Prometheus"), ("tempo", "Tempo"))
]

_id = [0]
_refs = "ABCDEFGHIJKLMNOP"


def norm(unit, decimals=None):
    """Number-format policy for EU/NL readers (Grafana always prints a decimal point and cannot localize).

    * big counts use SI scaling without a unit word (5.8 M, 501 k) instead of dotted thousands;
    * every other unit gets explicit decimals so auto-decimals can never produce a 3-digit fraction
      (a dot followed by exactly 3 digits reads as a thousands separator in NL).
    """
    if unit == "short":
        unit = "si:"
    if decimals is None:
        decimals = 1 if unit == "percentunit" else (None if unit == "si:" else 2)
    return unit, decimals


def nid():
    _id[0] += 1
    return _id[0]


# ---- targets ------------------------------------------------------------------------------------
def prom_targets(items, instant=False, fmt=None):
    out = []
    for i, it in enumerate(items):
        expr, legend = it if isinstance(it, tuple) else (it, "")
        t = {"datasource": PROM, "expr": expr, "legendFormat": legend, "refId": _refs[i], "instant": instant, "range": not instant}
        if fmt:
            t["format"] = fmt
        out.append(t)
    return out


def tq_targets(items, kind="range", step=None):
    """TraceQL metrics queries. kind is 'range' (time series) or 'instant' (one value per series over the dashboard range)."""
    out = []
    for i, query in enumerate(items):
        t = {"datasource": TEMPO, "refId": _refs[i], "queryType": "traceql", "query": query, "metricsQueryType": kind, "limit": 50}
        if step and kind == "range":
            t["step"] = step
        out.append(t)
    return out


def base(kind, title, x, y, w, h, ds, tg, desc=""):
    return {"id": nid(), "type": kind, "title": title, "description": desc,
            "gridPos": {"x": x, "y": y, "w": w, "h": h}, "datasource": ds, "targets": tg}


# ---- panels ---------------------------------------------------------------------------------------
def stat(title, expr, unit, x, y, w=4, h=4, ds=PROM, desc="", decimals=None, steps=None, bg=False, nv="0", mappings=None):
    """Plain numbers are neutral; only `steps` adds a good/bad colour. ds=TEMPO makes `expr` an instant TraceQL metrics query."""
    tg = tq_targets([expr], "instant") if ds is TEMPO else prom_targets([expr], instant=True)
    p = base("stat", title, x, y, w, h, ds, tg, desc)
    unit, decimals = norm(unit, decimals)
    d = {"unit": unit, "color": {"mode": "fixed", "fixedColor": "text"}, "noValue": nv, "mappings": mappings or []}
    if decimals is not None:
        d["decimals"] = decimals
    if steps:
        d["color"] = {"mode": "thresholds"}
        d["thresholds"] = {"mode": "absolute", "steps": steps}
        if ds is PROM and nv != "0":
            # An empty result would be coloured by the first threshold (red or green), which misreads as good or bad.
            # Return -1 instead and map it to grey text; no ratio, share or count here is ever negative.
            p["targets"][0]["expr"] = f"({expr}) or vector(-1)"
            grey = {"text": nv, "color": "text"}
            d["mappings"] = d["mappings"] + [
                {"type": "range", "options": {"from": -1.5, "to": -0.5, "result": {**grey, "index": 98}}},
                {"type": "special", "options": {"match": "null+nan", "result": {**grey, "index": 99}}}]   # 0 / 0 is NaN, not empty
    p["fieldConfig"] = {"defaults": d, "overrides": []}
    p["options"] = {"reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
                    "colorMode": "background" if bg else "value", "graphMode": "none", "textMode": "value", "justifyMode": "center"}
    return p


def ts(title, items, unit, x, y, w=12, h=8, ds=PROM, desc="", stack=False, bars=False, thr=None, overrides=None, step=None):
    """Time series. ds=TEMPO makes every item a range TraceQL metrics query (optionally at a fixed `step`)."""
    tg = tq_targets(items, "range", step) if ds is TEMPO else prom_targets(items)
    p = base("timeseries", title, x, y, w, h, ds, tg, desc)
    p["interval"] = "1m"   # minimum step: 15 s buckets hold 0-1 samples and make quantiles and bars jagged; 5 m left a 15 m view with 3 points
    custom = {"drawStyle": "bars" if bars else "line", "lineWidth": 2, "fillOpacity": 40 if (stack or bars) else 10,
              "showPoints": "auto", "pointSize": 5, "spanNulls": 1800000, "barAlignment": 0,
              "stacking": {"mode": "normal" if stack else "none", "group": "A"}}
    unit, dec = norm(unit)
    dflt = {"unit": unit, "custom": custom, "noValue": "none in this range", "min": 0}
    if dec is not None:
        dflt["decimals"] = dec
    if thr:   # dashed good/warn/bad lines so a glance shows where "bad" starts
        dflt["thresholds"] = {"mode": "absolute", "steps": thr}
        custom["thresholdsStyle"] = {"mode": "dashed"}
    p["fieldConfig"] = {"defaults": dflt, "overrides": overrides or []}
    p["options"] = {"legend": {"displayMode": "list", "placement": "bottom", "calcs": [], "showLegend": True},
                    "tooltip": {"mode": "multi", "sort": "desc"}}
    return p


def bargauge(title, expr, unit, x, y, w=8, h=7, ds=PROM, desc="", legend=""):
    """One bar per series. ds=TEMPO takes an instant TraceQL metrics query; the bar is named after the series."""
    tg = tq_targets([expr], "instant") if ds is TEMPO else prom_targets([(expr, legend)], instant=True)
    p = base("bargauge", title, x, y, w, h, ds, tg, desc)
    unit, dec = norm(unit)
    bd = {"unit": unit, "color": {"mode": "fixed", "fixedColor": "blue"}, "noValue": "none in this range", "min": 0}
    if ds is TEMPO:
        bd["displayName"] = "${__series.name}"
    elif legend:   # name from label values; a single series otherwise loses its name
        bd["displayName"] = legend.replace("{{", "${__field.labels.").replace("}}", "}")
    if dec is not None:
        bd["decimals"] = dec
    if unit == "percentunit":
        bd["max"] = 1
    p["fieldConfig"] = {"defaults": bd, "overrides": []}
    p["options"] = {"orientation": "horizontal", "displayMode": "gradient", "showUnfilled": True, "valueMode": "color",
                    "namePlacement": "top", "sizing": "manual", "minVizHeight": 40, "maxVizHeight": 48, "minVizWidth": 8,
                    "text": {"titleSize": 12, "valueSize": 13},
                    "reduceOptions": {"calcs": ["lastNotNull"], "values": False, "fields": ""}}
    return p


def tempo_table(title, query, x, y, w, h, table_type, desc="", rename=None, order=None, hide=None, sort=None, unit_overrides=None):
    p = base("table", title, x, y, w, h, TEMPO,
             [{"refId": "A", "datasource": TEMPO, "queryType": "traceql", "limit": 30, "tableType": table_type, "query": query}], desc)
    p["fieldConfig"] = {"defaults": {"custom": {"align": "auto"}, "noValue": "-"},
                        "overrides": unit_overrides or []}
    p["options"] = {"showHeader": True, "cellHeight": "sm"}
    alias = {"duration": "Duration", "time": "Start time", "spanID": "Span ID", "name": "Name"}
    rename = {**(rename or {}), **{alias[k]: v for k, v in (rename or {}).items() if k in alias}}   # Tempo names these columns itself
    tr = []
    if sort:
        tr.append({"id": "sortBy", "options": {"fields": {}, "sort": [{"field": alias.get(sort, sort), "desc": True}]}})
    index = {}
    for i, k in enumerate(order or []):
        index[k] = i
        if k in alias:
            index[alias[k]] = i
    tr.append({"id": "organize", "options": {
        "excludeByName": {**{k: True for k in (hide or [])}, **{alias[k]: True for k in (hide or []) if k in alias}},
        "indexByName": index,
        "renameByName": rename or {}}})
    p["transformations"] = tr
    return p


def all_panels(items):
    """Every panel, including the ones inside collapsed rows (they need the same post-processing)."""
    for p in items:
        yield p
        yield from all_panels(p.get("panels", []))


def row(title, y, children=None):
    """A row header. With `children` it is collapsed: the panels live inside the row and load when it is opened."""
    return {"id": nid(), "type": "row", "title": title, "collapsed": bool(children),
            "gridPos": {"x": 0, "y": y, "w": 24, "h": 1}, "panels": children or []}


# ---- shorthand selectors --------------------------------------------------------------------------
RI = "$__rate_interval"
RNG = "$__range"
BASE = "7d"
SVC = 'service=~"$service"'                           # Prometheus span-metric label
TSVC = 'resource.service.name =~ "${service:regex}"'   # TraceQL
ERR = 'status_code="STATUS_CODE_ERROR"'
NS = "span.paperclip.native.span."                    # native-run span attributes (closed allowlist, see telemetry-reference.md)
RUN = "task.provider_session"                         # root span of every native agent run


def sel(span, err=False, regex=False):
    """Span-metric selector for one span name (or a regex of names)."""
    op = "=~" if regex else "="
    return f'{{{SVC},span_name{op}"{span}"{"," + ERR if err else ""}}}'


def calls(span, err=False, regex=False):
    return "traces_spanmetrics_calls_total" + sel(span, err, regex)


def n(span, rng, err=False, regex=False):
    """Number of spans in a range, rounded because increase() extrapolates to the window edges (0 when there are none, so a ratio never goes empty)."""
    return f"(round(sum(increase({calls(span, err, regex)}[{rng}]))) or vector(0))"


def mean_s(span, rng):
    """Mean span duration in seconds over a range. Exact at any length, unlike a histogram quantile (buckets stop at 16.4 s)."""
    s = "traces_spanmetrics_latency_sum" + sel(span)
    c = "traces_spanmetrics_latency_count" + sel(span)
    return f"(sum(increase({s}[{rng}])) / sum(increase({c}[{rng}])))"


def per(span, unit_s, err=False, regex=False, by=None):
    """Span rate scaled to 'per hour' (3600) or 'per minute' (60), so the y axis means the same at every range."""
    e = f"rate({calls(span, err, regex)}[{RI}]) * {unit_s}"
    return f"sum by ({by}) ({e})" if by else f"sum({e})"


def tq(span, extra="", regex=False):
    """TraceQL span filter for one span name (or a regex of names), scoped to the selected instance(s)."""
    op = "=~" if regex else "="
    return f'{{ {TSVC} && name {op} "{span}"{" && " + extra if extra else ""} }}'


def quant(span, qs="0.5, 0.95", extra="", by=None, regex=False):
    return f"{tq(span, extra, regex)} | quantile_over_time(duration, {qs})" + (f" by ({by})" if by else "")


# Health judges everything against the user's OWN history, so it works in any setup:
#   * ratio tiles: value = (now over the dashboard range) / (usual over BASE); 1.0x = as usual
#   * the colour steps below are multiples of that baseline (not absolute numbers)
#   * counts of failures have a healthy baseline of exactly zero, so any occurrence is flagged
UP = [{"color": "green", "value": None}, {"color": "orange", "value": 1.5}, {"color": "red", "value": 2.5}]      # higher = worse
ANY = [{"color": "green", "value": None}, {"color": "orange", "value": 1}]
X = "suffix: x"   # unit for ratio tiles

panels = []
y = 0


def ratio_note(what):
    return f"{what} now (dashboard range) divided by the same figure over your last {BASE}: 1.0x = as usual. Orange from 1.5x, red from 2.5x."


def fail_ratio(span):
    """Failure share now vs usual, lightly smoothed (+1/+2) so a single early failure does not explode the ratio."""
    return (f"(({n(span, RNG, True)} + 1) / ({n(span, RNG)} + 2)) / (({n(span, BASE, True)} + 1) / ({n(span, BASE)} + 2))")


PRIOR_SPANS = 10   # how many spans of "usual" a window is worth before its own durations count


def mean_ratio(span):
    """Mean duration now vs usual, pulled toward the usual mean by a prior worth PRIOR_SPANS spans.

    A window with a handful of spans (a quiet 15 minutes) would otherwise swing the tile on noise alone. "No data" is kept
    for a window with no spans at all."""
    base = mean_s(span, BASE)
    total = f"sum(increase(traces_spanmetrics_latency_sum{sel(span)}[{RNG}]))"
    count = f"sum(increase(traces_spanmetrics_latency_count{sel(span)}[{RNG}]))"
    return f"(({total} + {PRIOR_SPANS} * {base}) / ({count} + {PRIOR_SPANS})) / {base} and ({count} > 0)"


# ---- what every run produces, whatever the adapter ------------------------------------------------
# task.execution_attempt is the server's root span for ONE invocation of the executor, for every adapter (claude_local,
# codex_local, paperclip_runner ...). The native runner's own lifecycle (task.provider_session and its children) only
# exists for paperclip_runner agents, and a native failure marks that span, not the attempt, so "failed" counts both.
ATTEMPT = "task.execution_attempt"
RUNS_RE = r"task\\.(execution_attempt|provider_session)"
SRV = 'span_kind="SPAN_KIND_SERVER"'
NATIVE_EMPTY = "no native runner runs in this range"


def failed(rng):
    return n(RUNS_RE, rng, True, regex=True)


PRIOR_RUNS = 10   # how many runs of "usual" a window is worth before its own failures count


def fail_ratio_runs():
    """Failed share of runs now vs usual, pulled toward the usual rate by a prior worth PRIOR_RUNS runs.

    A fixed +1/+2 smoothing turned a quiet 15-minute window with one run into a 3x alarm against a 7-day baseline of a few
    percent. With the baseline as the prior, a window of a few runs reads about 1.0x and only a real change moves it."""
    base = f"(({failed(BASE)} + 1) / ({n(ATTEMPT, BASE)} + 2))"
    now = f"(({failed(RNG)} + {PRIOR_RUNS} * {base}) / ({n(ATTEMPT, RNG)} + {PRIOR_RUNS}))"
    return f"{now} / {base}"


def srv_sel(err=False):
    return f'{{{SVC},{SRV}{"," + ERR if err else ""}}}'


def srv_n(rng, err=False):
    return f"(round(sum(increase(traces_spanmetrics_calls_total{srv_sel(err)}[{rng}]))) or vector(0))"


def srv_mean(rng):
    return (f"(sum(increase(traces_spanmetrics_latency_sum{srv_sel()}[{rng}])) / "
            f"sum(increase(traces_spanmetrics_latency_count{srv_sel()}[{rng}])))")


